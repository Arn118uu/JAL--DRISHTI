export const locations: Record<string, LocationRecord> = Object.fromEntries(
  records.map((r) => [r.id, r]),
)

export const locationList: LocationRecord[] = records

export const DEFAULT_LOCATION_ID = 'v-1'

export function getLocation(id: string | null): LocationRecord | null {
  if (!id) return null
  return locations[id] ?? null
}

// Seed a live-telemetry baseline from a location record so the simulation and
// charts always correspond to the currently selected location.
export function metricsForLocation(loc: LocationRecord): LiveMetrics {
  return {
    rainfall: loc.rainfall,
    soilMoisture: loc.soilMoisture,
    slopeStability: loc.slopeStability,
    riverLevel: loc.riverLevel,
    riverDanger: loc.riverDanger,
    floodProbability: loc.floodProbability,
    leadTimeMin: loc.leadTimeMin,
    confidence: loc.confidence,
    updatedAt: 0,
  }
}
