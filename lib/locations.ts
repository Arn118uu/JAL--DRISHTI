// Structured, backend-ready location data model for JAL-DRISHTI.
//
// The UI reads the selected location from application state:
//   selectedLocationId  ->  locations[selectedLocationId]
//
// This object map is intentionally decoupled from the UI so that a real
// ML / backend API can later replace `locations` without touching components.
// All numeric values here are DEMO / SIMULATED unless sourced from live sensors.

import type { LatLng, LiveMetrics, RiskLevel } from './disaster-data'

export type Coverage = 'full' | 'limited' | 'none'
export type LocationKind = 'flood' | 'glacier' | 'lake'

export interface LocationRecord {
  id: string
  kind: LocationKind
  name: string
  country: string
  state: string // State / Province
  district: string // District / region
  coord: LatLng // [lat, lng]
  isDemoArea: boolean // part of the SIH (Uttarakhand) demonstration area
  coverage: Coverage // prediction-data availability
  demo: boolean // values are simulated (true for the whole prototype)

  // Exposure
  population: number
  elevationM: number

  // Prediction
  floodProbability: number // 0-100
  risk: RiskLevel
  leadTimeMin: number
  confidence: number // 0-100

  // Drivers (latest reading)
  rainfall: number // mm/h
  soilMoisture: number // %VWC
  riverLevel: number // m
  riverDanger: number // m
  slopeStability: number // 0-100 (higher = more stable)

  // Context
  historicalRisk: string
  nearbyRiver: string
  nearbySensors: string[]
  alertStatus: string
  recommendedAction: string
}

